import type { BugRow } from "@/components/LogsBugs";

/** shareable markdown for a report — paste into chat, email, an issue tracker… */
export function reportMarkdown(r: BugRow): string {
  const lines = [
    `## Bug report — ${r.severity}`,
    "",
    `**Status:** ${r.status}`,
    `**Where:** ${r.page || "unknown"}`,
    `**Filed:** ${new Date(r.createdAt).toLocaleString()}`,
    "",
    r.desc,
  ];
  if (r.logs) lines.push("", "```", r.logs, "```");
  return lines.join("\n");
}

/** standalone HTML file with the screenshot embedded — send it to anyone, opens in any browser */
export function reportHtml(r: BugRow): string {
  const esc = (s: string) => s.replace(/&/g, "&amp;").replace(/</g, "&lt;").replace(/>/g, "&gt;");
  return `<!doctype html>
<html><head><meta charset="utf-8"><title>Nook bug report — ${esc(r.id.slice(0, 8))}</title>
<style>body{font:14px/1.6 system-ui,sans-serif;max-width:760px;margin:40px auto;padding:0 20px;color:#222}
h1{font-size:20px}code,pre{background:#f4f4f6;border-radius:6px;font-size:12px}pre{padding:12px;overflow:auto}
.chip{display:inline-block;background:#eee;border-radius:999px;padding:2px 10px;font-size:12px;margin-right:6px}
img{max-width:100%;border:1px solid #ddd;border-radius:10px;margin-top:12px}</style></head><body>
<h1>🐞 Nook bug report</h1>
<p><span class="chip">${esc(r.severity)}</span><span class="chip">${esc(r.status)}</span><span class="chip">${new Date(r.createdAt).toLocaleString()}</span></p>
<p><b>Where:</b> ${esc(r.page || "unknown")}<br><b>Report id:</b> ${esc(r.id)}</p>
<p>${esc(r.desc).replace(/\n/g, "<br>")}</p>
${r.logs ? `<pre>${esc(r.logs)}</pre>` : ""}
${r.screenshot ? `<img src="${r.screenshot}" alt="screenshot">` : ""}
<p style="color:#888;font-size:12px">Generated by Nook — Logs &amp; Bugs → My reports → Share</p>
</body></html>`;
}

export function downloadText(name: string, text: string, mime = "text/html") {
  const blob = new Blob([text], { type: mime });
  const a = document.createElement("a");
  a.href = URL.createObjectURL(blob);
  a.download = name;
  a.click();
  setTimeout(() => URL.revokeObjectURL(a.href), 4000);
}
